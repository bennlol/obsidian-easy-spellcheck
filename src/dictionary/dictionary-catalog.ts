export interface DownloadableDictionary {
  id: string;
  name: string;
  affUrl: string;
  dicUrl: string;
  licenseUrl?: string;
  licenseText?: string;
  sourceUrl: string;
}

const REVISION = "8cfea406b505e4d7df52d5a19bce525df98c54ab";
const RAW_ROOT = `https://raw.githubusercontent.com/wooorm/dictionaries/${REVISION}/dictionaries`;
const SOURCE_ROOT = `https://github.com/wooorm/dictionaries/tree/${REVISION}/dictionaries`;

function entry(id: string, name: string, licenseText?: string): DownloadableDictionary {
  const root = `${RAW_ROOT}/${id}`;
  return {
    id,
    name,
    affUrl: `${root}/index.aff`,
    dicUrl: `${root}/index.dic`,
    ...(licenseText === undefined ? { licenseUrl: `${root}/license` } : { licenseText }),
    sourceUrl: `${SOURCE_ROOT}/${id}`,
  };
}

